// =============================================================================
// File        : sar_afe_model.sv
// Project     : 8-bit Timer + 8-bit SAR ADC Peripheral (timer_adc8_uvm)
// Description : Behavioral Analog Front-End (AFE) Model containing a 4-to-1
//               Analog Multiplexer, Sample-and-Hold Capacitor, 8-bit Reference
//               DAC, and Analog Comparator (Chapter 6, Page 7).
// =============================================================================

`timescale 1ns/1ps // Define simulation time unit (1ns) and precision (1ps)

module sar_afe_model ( // Declare behavioral analog front-end simulation module
    input  logic       clk,        // System clock used to sample pseudo-random thermal noise
    input  logic       rst_n,      // Active-low asynchronous reset
    adc_if             afe         // Analog front-end SystemVerilog interface bundle
); // End of port list

    // -------------------------------------------------------------------------
    // Internal Real-Valued Analog Nodes and Pseudo-Random Noise State
    // -------------------------------------------------------------------------
    real           mux_out_v;      // Selected channel voltage at output of 4:1 analog mux
    real           vdac_v;         // Analog voltage generated by 8-bit internal DAC
    real           noise_sample_v; // Instantaneous noise voltage added during sampling
    int unsigned   lfsr_seed;      // Deterministic PRNG state for reproducible noise modeling

    // -------------------------------------------------------------------------
    // Continuous 4-to-1 Analog Multiplexer Selection
    // -------------------------------------------------------------------------
    always_comb begin              // Continuously select active analog sensor channel
        mux_out_v = afe.vin[afe.adc_ch]; // Route vin[0..3] based on 2-bit adc_ch
    end                            // End of analog multiplexer block

    // -------------------------------------------------------------------------
    // Sample-and-Hold Switch + Hold Capacitor Model (Track when sample=1, Hold when 0)
    // -------------------------------------------------------------------------
    always @(posedge clk or negedge rst_n) begin // Update noise generator on clock edge
        if (!rst_n) begin                        // Check if reset is active
            lfsr_seed      <= 32'hACE1_2026;     // Initialize deterministic noise seed
            noise_sample_v <= 0.0;               // Clear instantaneous noise term
        end else begin                           // Advance PRNG state on each clock
            lfsr_seed <= (lfsr_seed * 32'd1664525) + 32'd1013904223; // Linear congruential step
            if (afe.noise_amp_v > 0.0) begin     // Check if analog noise injection is enabled
                // Map signed 16-bit slice to [-noise_amp_v, +noise_amp_v]
                noise_sample_v <= ((real'(signed'(lfsr_seed[31:16]))) / 32768.0) * afe.noise_amp_v; // Execute statement per peripheral specification
            end else begin                       // Noise disabled
                noise_sample_v <= 0.0;           // Zero noise contribution
            end                                  // End of noise calculation
        end                                      // End of synchronous noise update
    end                                          // End of noise generator block

    // Track input voltage while adc_sample is high; hold last tracked voltage when low
    always @(*) begin                            // Continuous tracking while sample switch is closed
        if (!rst_n) begin                        // Reset capacitor voltage to 0.0V
            afe.vhold = 0.0;                     // Discharge sample-and-hold capacitor
        end else if (afe.adc_sample) begin       // Sample switch closed: track input + offset + noise
            afe.vhold = mux_out_v + afe.offset_v + noise_sample_v; // Charge hold capacitor
            if (afe.vhold < 0.0)      afe.vhold = 0.0;      // Clamp to ground rail (0.0V)
            if (afe.vhold > afe.vref) afe.vhold = afe.vref; // Clamp to reference rail (Vref)
        end                                      // When adc_sample == 0, afe.vhold retains its held value
    end                                          // End of sample-and-hold block

    // -------------------------------------------------------------------------
    // 8-bit DAC and Comparator: Is held voltage (Vhold) >= trial DAC voltage (Vdac)?
    // -------------------------------------------------------------------------
    always_comb begin                            // Evaluate 8-bit DAC and comparator continuously
        vdac_v      = (real'(afe.adc_dac) * afe.vref) / 256.0; // Vdac = dac_code * Vref / 256
        afe.adc_cmp = (afe.vhold + 1.0e-9 >= vdac_v) ? 1'b1 : 1'b0; // Comparator decision (1: keep bit)
    end                                          // End of DAC and comparator block

endmodule // End of sar_afe_model module
